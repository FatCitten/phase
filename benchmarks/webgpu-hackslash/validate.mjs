import { readFileSync, existsSync } from 'node:fs';
const must=(cond,msg)=>{if(!cond){console.error(`FAIL ${msg}`);process.exitCode=1}else console.log(`PASS ${msg}`)};
for(const f of ['index.html','src/game.js','src/shader.wgsl'])must(existsSync(f),`${f} exists`);
const js=readFileSync('src/game.js','utf8'), wgsl=readFileSync('src/shader.wgsl','utf8');
must(js.includes('navigator.gpu.requestAdapter'),'requests a WebGPU adapter');
must(js.includes('navigator.gpu.getPreferredCanvasFormat()'),'uses preferred canvas format');
must(js.includes("getContext('webgpu')"),'uses WebGPU canvas context');
must(js.includes('requestPointerLock'),'supports mouse-look pointer lock');
must(js.includes('e.hp-=1'),'implements melee damage');
must(js.includes("keys.has('KeyW')"),'implements WASD movement');
must(wgsl.includes('fn castRay'),'WGSL contains ray caster');
must(wgsl.includes('wallAt'),'WGSL performs grid wall tests');
must(wgsl.includes('enemyPixel'),'WGSL renders enemies in ray space');
must(wgsl.includes('@fragment'),'WGSL has fragment stage');
